import { describe, expect, it } from 'vitest';
import {
  generateRandomDemoQrJson,
  parsePackageQrPayload,
} from './qrPackageParser';

describe('qrPackageParser', () => {
  it('parses structured SLS package JSON generated by qr-helper', () => {
    const rawJson = JSON.stringify({
      trackingCode: 'SLS-2026-48201',
      sender: 'Almacenes del Caribe S.A.S.',
      recipient: 'Droguería La Economía Norte',
      recipientAddress: 'Cra 53 # 82-45, Riomar, Barranquilla',
      recipientPhone: '+57 300 412 8890',
      municipalityCode: '08001',
      zone: 'Zona Norte',
      zoneId: '08d92a06-4921-4989-92ff-f1917240779c',
      sector: 'Sector A',
      sectorId: '2ef99933-082e-4d24-b1a1-b5c574ca6aa5',
      shipmentType: 'Express',
      shipmentTypeId: 'b268c5c7-b2b5-411d-b734-07746ae7e6e6',
      priority: 'urgent',
      weightKg: 3.4,
      lengthCm: 35,
      widthCm: 25,
      heightCm: 20,
      volume: 17.5,
      latitude: 11.0085,
      longitude: -74.8152,
      notes: 'Entregar en recepción principal antes de las 4:00 p. m.',
    });

    const parsed = parsePackageQrPayload(rawJson);

    expect(parsed.isStructuredJson).toBe(true);
    expect(parsed.trackingCode).toBe('SLS-2026-48201');
    expect(parsed.sender).toBe('Almacenes del Caribe S.A.S.');
    expect(parsed.recipient).toBe('Droguería La Economía Norte');
    expect(parsed.recipientAddress).toBe(
      'Cra 53 # 82-45, Riomar, Barranquilla',
    );
    expect(parsed.recipientPhone).toBe('+57 300 412 8890');
    expect(parsed.zone).toBe('Zona Norte');
    expect(parsed.sector).toBe('Sector A');
    expect(parsed.shipmentType).toBe('Express');
    expect(parsed.priority).toBe('urgent');
    expect(parsed.backendPriority).toBe('HIGH');
    expect(parsed.weightKg).toBe(3.4);
    expect(parsed.lengthCm).toBe(35);
    expect(parsed.widthCm).toBe(25);
    expect(parsed.heightCm).toBe(20);
    expect(parsed.volumeLiters).toBe(17.5);
    expect(parsed.latitude).toBe(11.0085);
    expect(parsed.longitude).toBe(-74.8152);
  });

  it('generates and parses random demo QR JSON payloads with valid structure', () => {
    const rawJson = generateRandomDemoQrJson();
    const parsed = parsePackageQrPayload(rawJson);

    expect(parsed.isStructuredJson).toBe(true);
    expect(parsed.trackingCode).toMatch(/^SLS-2026-\d{5}$/);
    expect(parsed.recipient.length).toBeGreaterThan(0);
    expect(parsed.recipientAddress).toContain('Barranquilla');
    expect(parsed.weightKg).toBeGreaterThan(0);
    expect(parsed.volumeLiters).toBeGreaterThan(0);
  });

  it('falls back to plain trackingCode when QR contains plain text', () => {
    const parsed = parsePackageQrPayload('SLS-2026-00999');

    expect(parsed.isStructuredJson).toBe(false);
    expect(parsed.trackingCode).toBe('SLS-2026-00999');
  });

  it('throws when QR content is empty', () => {
    expect(() => parsePackageQrPayload('   ')).toThrow(
      'El código QR está vacío.',
    );
  });
});
